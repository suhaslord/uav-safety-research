from __future__ import annotations

from pathlib import Path
import argparse
import json

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from .metrics import summarize
from .perception import PROFILES
from .simulator import run_episode
from .config import SupervisorConfig


def run_monte_carlo(episodes_per_cell: int, seed: int, sup_cfg: SupervisorConfig | None = None) -> tuple[pd.DataFrame, pd.DataFrame]:
    seed_rng = np.random.default_rng(seed)
    rows = []

    for profile in PROFILES:
        for supervised in (False, True):
            for _ in range(episodes_per_cell):
                episode_seed = int(seed_rng.integers(0, 2**31 - 1))
                rows.append(run_episode(
                    seed=episode_seed,
                    profile=profile,
                    supervised=supervised,
                    sup_cfg=sup_cfg,
                ).to_dict())

    raw = pd.DataFrame(rows)
    return raw, summarize(raw)


def save_outputs(raw: pd.DataFrame, summary: pd.DataFrame, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    raw.to_csv(out_dir / "episodes.csv", index=False)
    summary.to_csv(out_dir / "summary.csv", index=False)

    meta = {
        "episodes": int(len(raw)),
        "profiles": sorted(raw["profile"].unique().tolist()),
        "controllers": ["baseline", "supervised"],
    }
    (out_dir / "run_metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    _plot_unsafe_rate(summary, out_dir / "unsafe_touchdown_rate.png")
    _plot_success_rate(summary, out_dir / "success_rate.png")
    _write_markdown(summary, out_dir / "summary.md")


def _plot_unsafe_rate(summary: pd.DataFrame, path: Path) -> None:
    pivot = summary.pivot(index="profile", columns="controller", values="unsafe_touchdown_rate")
    pivot.plot(kind="bar")
    plt.ylabel("Unsafe touchdown rate")
    plt.xlabel("Perception degradation profile")
    plt.title("Unsafe touchdown rate: baseline vs safety supervisor")
    plt.ylim(0, 1)
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def _plot_success_rate(summary: pd.DataFrame, path: Path) -> None:
    pivot = summary.pivot(index="profile", columns="controller", values="success_rate")
    pivot.plot(kind="bar")
    plt.ylabel("Successful landing rate")
    plt.xlabel("Perception degradation profile")
    plt.title("Landing success rate by perception condition")
    plt.ylim(0, 1)
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def _write_markdown(summary: pd.DataFrame, path: Path) -> None:
    display = summary.copy()
    for col in [
        "success_rate", "unsafe_touchdown_rate", "abort_rate",
        "mean_final_x_error", "mean_interventions", "mean_max_risk",
    ]:
        display[col] = display[col].map(lambda x: f"{x:.3f}")
    path.write_text(
        "# Experiment Summary\n\n"
        "Generated by the reproducible Monte Carlo experiment runner.\n\n"
        + display[[
            "profile", "controller", "episodes", "success_rate",
            "unsafe_touchdown_rate", "abort_rate", "mean_final_x_error",
            "mean_interventions", "mean_max_risk",
        ]].to_markdown(index=False)
        + "\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Run AegisLand Monte Carlo experiments.")
    parser.add_argument("--episodes", type=int, default=100, help="Episodes per profile/controller cell.")
    parser.add_argument("--seed", type=int, default=2026, help="Top-level reproducibility seed.")
    parser.add_argument("--out", type=Path, default=Path("results/latest"))
    args = parser.parse_args()

    raw, summary = run_monte_carlo(args.episodes, args.seed)
    save_outputs(raw, summary, args.out)
    print(summary.to_string(index=False))
    print(f"\nSaved results to {args.out}")


if __name__ == "__main__":
    main()
